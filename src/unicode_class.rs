//! The three Unicode character classes the built-in PII patterns use.
//!
//! The built-in patterns in [`crate::sanitize`] were written as `regex` crate
//! patterns, where `\d`, `\s` and `\w` (and so `\b`) are Unicode-aware by
//! default. Matching them without that crate means carrying the same three
//! classes here: `\d` is `\p{Nd}`, `\s` is `\p{White_Space}`, and `\w` is
//! `[\p{Alphabetic}\p{M}\p{Nd}\p{Pc}\p{Join_Control}]`.
//!
//! The tables are copied from the `regex-syntax` release the full artifact
//! links, so both artifacts redact identically. `tables_match_regex_syntax`
//! below fails if they drift, and `print_tables` regenerates them:
//! `cargo test --lib unicode_class::tests::print_tables -- --ignored --nocapture`.

/// `\d` in the `regex` crate's Unicode mode.
pub(crate) fn is_digit(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_digit();
    }
    in_table(DECIMAL_NUMBER, c)
}

/// `\s` in the `regex` crate's Unicode mode.
pub(crate) fn is_space(c: char) -> bool {
    if c.is_ascii() {
        return c == ' ' || ('\t'..='\r').contains(&c);
    }
    in_table(WHITE_SPACE, c)
}

/// `\w` in the `regex` crate's Unicode mode, which is what decides `\b`.
pub(crate) fn is_word(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_alphanumeric() || c == '_';
    }
    in_table(PERL_WORD, c)
}

fn in_table(table: &[(char, char)], c: char) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

